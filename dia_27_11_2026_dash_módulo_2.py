#vamos fazer os imports necessários para construção do dash
import pandas as pd
import plotly.express as px
import streamlit as st

#configurando minha página para aparecer no topo a palavra DashCovid e usar toda a tela
st.set_page_config(page_title='DashCovid', layout='wide')

#vamos dar um titulo para nosso dashboard
st.title('DASHCOVID: Um dashboard sobre dados de Covid-19 - Ano 2020')

df = pd.read_csv('WHO_time_series.csv')

df.head()

fig1 = px.line(df, x = 'Date_reported', y = 'Cumulative_cases',
               color = 'Country', title = 'Dados de Covid-19 no mundo - Segundo a OMS')
fig1.update_layout(xaxis_title='Data', yaxis_title='Número de Casos Acumulados',
                   title_font_size=30)
fig1.show()

st.plotly_chart(fig1, use_container_width=True)

